#!/usr/bin/env node
/**
 * TSM Runtime V2 — Phase 44: Solution Packaging / Marketplace Productization
 *
 * You already have marketplace infrastructure (Marketplace, Connectors,
 * Customer Provisioning). This layer productizes it: it defines a "Solution
 * Pack" as a declarative manifest bundling agents, rules, policies, workflow
 * templates, and dashboards for a specific vertical/customer segment (e.g.
 * "TSM Healthcare Pack"), and provides the build/register/install/validate
 * lifecycle around that manifest.
 *
 * This does not replace Marketplace -- it is the format Marketplace listings
 * are built from, and the mechanism Customer Provisioning installs against.
 *
 * Usage: node scripts/runtime-migration/44-runtime-solution-packaging-layer.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join('html', 'shared', 'runtime', 'solution-packaging');

const files = {};

// ---------------------------------------------------------------------------
files['pack-manifest-engine.js'] = [
"/**",
" * pack-manifest-engine.js",
" *",
" * Defines and validates the Solution Pack manifest schema. A pack is a",
" * declarative bundle of the pieces a vertical deployment needs -- it does",
" * not contain the actual engine code, only references to it, so packs",
" * stay lightweight and versioned independently of the runtime itself.",
" */",
"",
"const REQUIRED_FIELDS = ['packId', 'name', 'vertical', 'version', 'components'];",
"const COMPONENT_TYPES = ['agent', 'rule', 'policy', 'workflowTemplate', 'dashboard', 'connector'];",
"",
"function createManifest(input) {",
"  const manifest = {",
"    packId: input.packId,",
"    name: input.name,",
"    vertical: input.vertical,",
"    version: input.version || '1.0.0',",
"    description: input.description || '',",
"    components: input.components || [],",
"    createdAt: new Date().toISOString(),",
"  };",
"  return manifest;",
"}",
"",
"function validateManifest(manifest) {",
"  const errors = [];",
"",
"  REQUIRED_FIELDS.forEach(function (field) {",
"    if (!manifest || manifest[field] === undefined || manifest[field] === null) {",
"      errors.push('Missing required field: ' + field);",
"    }",
"  });",
"",
"  if (manifest && Array.isArray(manifest.components)) {",
"    manifest.components.forEach(function (c, idx) {",
"      if (!c.type || COMPONENT_TYPES.indexOf(c.type) === -1) {",
"        errors.push('components[' + idx + '].type must be one of: ' + COMPONENT_TYPES.join(', '));",
"      }",
"      if (!c.ref) {",
"        errors.push('components[' + idx + '].ref is required (path or id of the referenced artifact)');",
"      }",
"    });",
"  } else if (manifest) {",
"    errors.push('components must be an array');",
"  }",
"",
"  return { valid: errors.length === 0, errors: errors };",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { REQUIRED_FIELDS: REQUIRED_FIELDS, COMPONENT_TYPES: COMPONENT_TYPES, createManifest: createManifest, validateManifest: validateManifest };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.packManifest = { createManifest: createManifest, validateManifest: validateManifest };",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['pack-builder.js'] = [
"/**",
" * pack-builder.js",
" *",
" * Convenience builder for assembling a manifest from existing platform",
" * artifacts, e.g. turning the BPO chain plus its rules/dashboards into a",
" * 'TSM BPO Enterprise Pack' without hand-writing the manifest JSON.",
" */",
"",
"class PackBuilder {",
"  constructor(packId, name, vertical) {",
"    this.packId = packId;",
"    this.name = name;",
"    this.vertical = vertical;",
"    this.components = [];",
"    this.version = '1.0.0';",
"    this.description = '';",
"  }",
"",
"  setVersion(version) {",
"    this.version = version;",
"    return this;",
"  }",
"",
"  setDescription(description) {",
"    this.description = description;",
"    return this;",
"  }",
"",
"  addAgent(ref, meta) {",
"    this.components.push({ type: 'agent', ref: ref, meta: meta || {} });",
"    return this;",
"  }",
"",
"  addRule(ref, meta) {",
"    this.components.push({ type: 'rule', ref: ref, meta: meta || {} });",
"    return this;",
"  }",
"",
"  addPolicy(ref, meta) {",
"    this.components.push({ type: 'policy', ref: ref, meta: meta || {} });",
"    return this;",
"  }",
"",
"  addWorkflowTemplate(ref, meta) {",
"    this.components.push({ type: 'workflowTemplate', ref: ref, meta: meta || {} });",
"    return this;",
"  }",
"",
"  addDashboard(ref, meta) {",
"    this.components.push({ type: 'dashboard', ref: ref, meta: meta || {} });",
"    return this;",
"  }",
"",
"  addConnector(ref, meta) {",
"    this.components.push({ type: 'connector', ref: ref, meta: meta || {} });",
"    return this;",
"  }",
"",
"  build(createManifest) {",
"    return createManifest({",
"      packId: this.packId,",
"      name: this.name,",
"      vertical: this.vertical,",
"      version: this.version,",
"      description: this.description,",
"      components: this.components,",
"    });",
"  }",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { PackBuilder: PackBuilder };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.PackBuilder = PackBuilder;",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['pack-registry.js'] = [
"/**",
" * pack-registry.js",
" *",
" * In-memory (or localStorage-backed) registry of built solution packs.",
" * The existing Marketplace UI reads from this registry to list what's",
" * available; Customer Provisioning reads from it to know what to install.",
" */",
"",
"const STORE_KEY = 'tsm.solutionPacks.registry.v1';",
"",
"class PackRegistry {",
"  constructor() {",
"    this._mem = {};",
"    this._loaded = false;",
"  }",
"",
"  _load() {",
"    if (this._loaded) return;",
"    this._loaded = true;",
"    try {",
"      if (typeof localStorage !== 'undefined') {",
"        const raw = localStorage.getItem(STORE_KEY);",
"        this._mem = raw ? JSON.parse(raw) : {};",
"      }",
"    } catch (e) {",
"      this._mem = {};",
"    }",
"  }",
"",
"  _persist() {",
"    try {",
"      if (typeof localStorage !== 'undefined') {",
"        localStorage.setItem(STORE_KEY, JSON.stringify(this._mem));",
"      }",
"    } catch (e) {",
"      // ignore",
"    }",
"  }",
"",
"  register(manifest, validateManifest) {",
"    this._load();",
"    const result = validateManifest(manifest);",
"    if (!result.valid) {",
"      throw new Error('Cannot register invalid pack: ' + result.errors.join('; '));",
"    }",
"    this._mem[manifest.packId] = manifest;",
"    this._persist();",
"    return manifest;",
"  }",
"",
"  get(packId) {",
"    this._load();",
"    return this._mem[packId] || null;",
"  }",
"",
"  listByVertical(vertical) {",
"    this._load();",
"    return Object.keys(this._mem)",
"      .map((id) => this._mem[id])",
"      .filter((p) => !vertical || p.vertical === vertical);",
"  }",
"",
"  all() {",
"    this._load();",
"    return Object.keys(this._mem).map((id) => this._mem[id]);",
"  }",
"}",
"",
"const packRegistry = new PackRegistry();",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { PackRegistry: PackRegistry, packRegistry: packRegistry };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.packRegistry = packRegistry;",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['pack-installer.js'] = [
"/**",
" * pack-installer.js",
" *",
" * Simulates/executes installation of a pack into a target tenant context.",
" * In this scaffold, 'installing' means resolving each component reference",
" * and recording an install record -- the actual wiring into a live tenant",
" * environment is the responsibility of Phase 45's deployment fabric, which",
" * this module is designed to hand off to.",
" */",
"",
"function installPack(manifest, tenantId, opts) {",
"  opts = opts || {};",
"  const results = manifest.components.map(function (component) {",
"    return {",
"      type: component.type,",
"      ref: component.ref,",
"      status: 'resolved',",
"      installedAt: new Date().toISOString(),",
"    };",
"  });",
"",
"  const installRecord = {",
"    tenantId: tenantId,",
"    packId: manifest.packId,",
"    packVersion: manifest.version,",
"    componentResults: results,",
"    installedAt: new Date().toISOString(),",
"    installedBy: opts.installedBy || 'system',",
"  };",
"",
"  if (typeof TSM !== 'undefined' && TSM.relay && TSM.relay.write) {",
"    TSM.relay.write('SOLUTION_PACKAGING', { type: 'pack_installed', installRecord: installRecord });",
"  }",
"",
"  return installRecord;",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { installPack: installPack };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.installPack = installPack;",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['pack-validator.js'] = [
"/**",
" * pack-validator.js",
" *",
" * Pre-install validation beyond basic manifest shape: checks that every",
" * referenced component actually exists in the provided catalog (e.g. a",
" * registry of known agents/rules/dashboards), and flags version",
" * mismatches. Intended to run in CI (alongside parse-gate.yml) before a",
" * pack is published to the marketplace.",
" */",
"",
"function validatePackAgainstCatalog(manifest, catalog) {",
"  catalog = catalog || {};",
"  const missing = [];",
"  const versionWarnings = [];",
"",
"  manifest.components.forEach(function (component) {",
"    const catalogEntry = catalog[component.ref];",
"    if (!catalogEntry) {",
"      missing.push({ type: component.type, ref: component.ref });",
"      return;",
"    }",
"    if (component.meta && component.meta.expectedVersion && catalogEntry.version) {",
"      if (component.meta.expectedVersion !== catalogEntry.version) {",
"        versionWarnings.push({",
"          ref: component.ref,",
"          expected: component.meta.expectedVersion,",
"          actual: catalogEntry.version,",
"        });",
"      }",
"    }",
"  });",
"",
"  return {",
"    packId: manifest.packId,",
"    valid: missing.length === 0,",
"    missingComponents: missing,",
"    versionWarnings: versionWarnings,",
"    checkedAt: new Date().toISOString(),",
"  };",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { validatePackAgainstCatalog: validatePackAgainstCatalog };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.validatePackAgainstCatalog = validatePackAgainstCatalog;",
"}",
""
].join('\n');

