#!/usr/bin/env node
/**
 * TSM Runtime V2 — Phase 46: External AI Model Governance
 *
 * You currently call Groq directly via tsmGroqComplete / GROQ_API_KEY in
 * several places (the collective BNCA and WIP command center routes, at
 * least). This layer sits in front of that: a registry of which models are
 * approved for which use, a router that picks one, an evaluation harness,
 * a drift/hallucination monitor, and cost tracking -- all decoupled from
 * any single provider so adding OpenAI/Gemini/Azure later doesn't mean
 * touching every route that calls a model today.
 *
 * This is additive: existing direct tsmGroqComplete calls keep working.
 * Routes migrate to routeModelCall() opportunistically.
 *
 * Usage: node scripts/runtime-migration/46-runtime-model-governance-layer.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join('html', 'shared', 'runtime', 'model-governance');

const files = {};

// ---------------------------------------------------------------------------
files['model-registry.js'] = [
"/**",
" * model-registry.js",
" *",
" * Declares which models are known to the platform, what they're approved",
" * for, and their basic cost/latency profile. Nothing calls a model",
" * directly from here -- this is metadata that model-routing.js consumes.",
" */",
"",
"const MODELS = {",
"  'groq:llama-3.1-70b': {",
"    provider: 'groq',",
"    modelId: 'llama-3.1-70b-versatile',",
"    approvedFor: ['general', 'strategist', 'situation-room', 'collective-bnca', 'wip-command-center'],",
"    costPer1kTokensUsd: 0.00059,",
"    avgLatencyMs: 700,",
"    status: 'active',",
"  },",
"  'groq:llama-3.1-8b': {",
"    provider: 'groq',",
"    modelId: 'llama-3.1-8b-instant',",
"    approvedFor: ['general', 'quick-classification'],",
"    costPer1kTokensUsd: 0.00005,",
"    avgLatencyMs: 250,",
"    status: 'active',",
"  },",
"};",
"",
"function getModel(key) {",
"  const model = MODELS[key];",
"  if (!model) throw new Error('Unknown model: ' + key);",
"  return Object.assign({ key: key }, model);",
"}",
"",
"function listApprovedFor(useCase) {",
"  return Object.keys(MODELS)",
"    .filter((key) => MODELS[key].approvedFor.indexOf(useCase) !== -1 && MODELS[key].status === 'active')",
"    .map((key) => Object.assign({ key: key }, MODELS[key]));",
"}",
"",
"function registerModel(key, definition) {",
"  MODELS[key] = Object.assign({ status: 'active' }, definition);",
"  return getModel(key);",
"}",
"",
"function deprecateModel(key) {",
"  if (!MODELS[key]) throw new Error('Unknown model: ' + key);",
"  MODELS[key].status = 'deprecated';",
"  return getModel(key);",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { MODELS: MODELS, getModel: getModel, listApprovedFor: listApprovedFor, registerModel: registerModel, deprecateModel: deprecateModel };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.modelRegistry = { getModel: getModel, listApprovedFor: listApprovedFor, registerModel: registerModel, deprecateModel: deprecateModel };",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['model-routing.js'] = [
"/**",
" * model-routing.js",
" *",
" * Picks a model for a given use case and calls it through a supplied",
" * provider adapter map, so routes stop hardcoding tsmGroqComplete and",
" * instead express intent ('I need a strategist-quality completion') and",
" * let this module resolve which model/provider actually serves it.",
" *",
" * providerAdapters shape: { groq: async (modelId, prompt, opts) => text, ... }",
" */",
"",
"async function routeModelCall(useCase, prompt, deps) {",
"  deps = deps || {};",
"  const listApprovedFor = deps.listApprovedFor;",
"  const providerAdapters = deps.providerAdapters || {};",
"  const preferredKey = deps.preferredModelKey || null;",
"  const opts = deps.opts || {};",
"",
"  if (!listApprovedFor) {",
"    throw new Error('model-routing requires listApprovedFor from model-registry');",
"  }",
"",
"  const candidates = listApprovedFor(useCase);",
"  if (!candidates.length) {",
"    throw new Error('No approved model for use case: ' + useCase);",
"  }",
"",
"  const chosen = preferredKey",
"    ? candidates.find((c) => c.key === preferredKey) || candidates[0]",
"    : candidates[0];",
"",
"  const adapter = providerAdapters[chosen.provider];",
"  if (!adapter) {",
"    throw new Error('No provider adapter registered for: ' + chosen.provider);",
"  }",
"",
"  const startedAt = Date.now();",
"  const text = await adapter(chosen.modelId, prompt, opts);",
"  const latencyMs = Date.now() - startedAt;",
"",
"  return {",
"    useCase: useCase,",
"    modelKey: chosen.key,",
"    provider: chosen.provider,",
"    text: text,",
"    latencyMs: latencyMs,",
"    calledAt: new Date().toISOString(),",
"  };",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { routeModelCall: routeModelCall };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.routeModelCall = routeModelCall;",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['model-evaluation.js'] = [
"/**",
" * model-evaluation.js",
" *",
" * Lightweight scored-eval harness: run a fixed set of prompts against a",
" * model/provider pair and record pass/fail against expected-substring or",
" * custom scoring functions, so swapping a model version doesn't silently",
" * change strategist output quality.",
" */",
"",
"async function runEvalSuite(modelKey, testCases, deps) {",
"  deps = deps || {};",
"  const routeModelCall = deps.routeModelCall;",
"  const listApprovedFor = deps.listApprovedFor;",
"  const providerAdapters = deps.providerAdapters;",
"",
"  const results = [];",
"",
"  for (const testCase of testCases) {",
"    let passed = false;",
"    let output = null;",
"    let error = null;",
"",
"    try {",
"      const response = await routeModelCall(testCase.useCase || 'general', testCase.prompt, {",
"        listApprovedFor: listApprovedFor,",
"        providerAdapters: providerAdapters,",
"        preferredModelKey: modelKey,",
"      });",
"      output = response.text;",
"      passed = typeof testCase.score === 'function'",
"        ? !!testCase.score(output)",
"        : (testCase.expectedSubstring ? output.indexOf(testCase.expectedSubstring) !== -1 : true);",
"    } catch (err) {",
"      error = String(err && err.message ? err.message : err);",
"    }",
"",
"    results.push({ name: testCase.name, passed: passed, output: output, error: error });",
"  }",
"",
"  const passCount = results.filter((r) => r.passed).length;",
"",
"  return {",
"    modelKey: modelKey,",
"    total: results.length,",
"    passed: passCount,",
"    failed: results.length - passCount,",
"    results: results,",
"    ranAt: new Date().toISOString(),",
"  };",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { runEvalSuite: runEvalSuite };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.runEvalSuite = runEvalSuite;",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['hallucination-monitor.js'] = [
"/**",
" * hallucination-monitor.js",
" *",
" * Heuristic, not magic: flags model outputs that cite data references",
" * (dataRefs) not present in the context that was actually sent, or that",
" * exceed a confidence claim without evidence attached. Meant to feed",
" * Phase 42's evidence ledger with a 'flagged' status rather than to block",
" * anything automatically -- a human reviews flags.",
" */",
"",
"function checkForUnsupportedClaims(output, contextDataRefs) {",
"  const knownRefs = new Set(contextDataRefs || []);",
"  const citedRefPattern = /\\[ref:([a-zA-Z0-9_\\-]+)\\]/g;",
"  const flags = [];",
"  let match;",
"",
"  while ((match = citedRefPattern.exec(output)) !== null) {",
"    const ref = match[1];",
"    if (!knownRefs.has(ref)) {",
"      flags.push({ type: 'unsupported_reference', ref: ref });",
"    }",
"  }",
"",
"  return { hasFlags: flags.length > 0, flags: flags };",
"}",
"",
"function checkConfidenceConsistency(output, declaredConfidence, minEvidenceItems) {",
"  const evidenceMentions = (output.match(/\\[ref:[a-zA-Z0-9_\\-]+\\]/g) || []).length;",
"  const threshold = minEvidenceItems != null ? minEvidenceItems : 1;",
"",
"  if (declaredConfidence != null && declaredConfidence > 0.8 && evidenceMentions < threshold) {",
"    return {",
"      consistent: false,",
"      reason: 'High confidence (' + declaredConfidence + ') declared with only ' + evidenceMentions + ' evidence reference(s).',",
"    };",
"  }",
"",
"  return { consistent: true, reason: null };",
"}",
"",
"function evaluateOutput(output, opts) {",
"  opts = opts || {};",
"  const refCheck = checkForUnsupportedClaims(output, opts.contextDataRefs);",
"  const confCheck = checkConfidenceConsistency(output, opts.declaredConfidence, opts.minEvidenceItems);",
"",
"  return {",
"    flaggedForReview: refCheck.hasFlags || !confCheck.consistent,",
"    unsupportedReferences: refCheck.flags,",
"    confidenceCheck: confCheck,",
"    evaluatedAt: new Date().toISOString(),",
"  };",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { checkForUnsupportedClaims: checkForUnsupportedClaims, checkConfidenceConsistency: checkConfidenceConsistency, evaluateOutput: evaluateOutput };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.hallucinationMonitor = { evaluateOutput: evaluateOutput };",
"}",
""
].join('\n');

