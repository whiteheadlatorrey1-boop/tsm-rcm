#!/usr/bin/env node
/**
 * TSM Runtime V2 — Phase 43: Enterprise Identity & Role Intelligence
 *
 * You already have Security (authn/authz gate-keeping). This layer adds
 * behavioral identity on top: it shapes WHAT a given user sees and in what
 * form, based on their role -- so an executive gets a risk summary, an
 * analyst gets evidence, an operator gets tasks, and an auditor gets
 * history, all from the same underlying decision.
 *
 * This does not replace Security/Governance. It reads role + behavior and
 * emits a presentation profile that portals can use to filter/reshape what
 * they render. It never grants access on its own.
 *
 * Usage: node scripts/runtime-migration/43-runtime-identity-intelligence-layer.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join('html', 'shared', 'runtime', 'identity');

const files = {};

// ---------------------------------------------------------------------------
files['role-intelligence.js'] = [
"/**",
" * role-intelligence.js",
" *",
" * Maps a role to a presentation profile: what kind of content that role",
" * should be shown by default, and in what density/format. Vertical",
" * executive portals and war rooms consult this to decide which panels to",
" * surface, not to decide what data the user is authorized to see -- that",
" * remains Security/Governance's job.",
" */",
"",
"const ROLE_PROFILES = {",
"  executive: {",
"    label: 'Executive',",
"    view: 'risk-summary',",
"    density: 'low',",
"    prioritize: ['riskScore', 'financialImpact', 'trendDirection', 'recommendation'],",
"    hide: ['rawEvidence', 'queryLogs'],",
"  },",
"  analyst: {",
"    label: 'Analyst',",
"    view: 'evidence',",
"    density: 'high',",
"    prioritize: ['dataRefs', 'ruleTrace', 'confidence', 'outliers'],",
"    hide: [],",
"  },",
"  operator: {",
"    label: 'Operator',",
"    view: 'tasks',",
"    density: 'medium',",
"    prioritize: ['queue', 'slaCountdown', 'nextAction'],",
"    hide: ['strategicNarrative'],",
"  },",
"  auditor: {",
"    label: 'Auditor',",
"    view: 'history',",
"    density: 'high',",
"    prioritize: ['auditTrail', 'approvals', 'outcomes', 'timestamps'],",
"    hide: ['recommendation'],",
"  },",
"  admin: {",
"    label: 'Administrator',",
"    view: 'system',",
"    density: 'high',",
"    prioritize: ['systemHealth', 'userManagement', 'configuration'],",
"    hide: [],",
"  },",
"};",
"",
"const DEFAULT_PROFILE = ROLE_PROFILES.operator;",
"",
"function getProfileForRole(role) {",
"  return ROLE_PROFILES[role] || Object.assign({}, DEFAULT_PROFILE, { label: role || 'Unknown' });",
"}",
"",
"function listRoles() {",
"  return Object.keys(ROLE_PROFILES);",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { ROLE_PROFILES: ROLE_PROFILES, getProfileForRole: getProfileForRole, listRoles: listRoles };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.roleIntelligence = { ROLE_PROFILES: ROLE_PROFILES, getProfileForRole: getProfileForRole, listRoles: listRoles };",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['user-profile-engine.js'] = [
"/**",
" * user-profile-engine.js",
" *",
" * Lightweight per-user profile: declared role, observed vertical usage,",
" * and last-seen preferences. Not an identity provider -- assumes",
" * authentication has already happened upstream (Security layer) and this",
" * just enriches the authenticated user with platform-specific context.",
" */",
"",
"const STORE_KEY_PREFIX = 'tsm.identity.userProfile.';",
"",
"class UserProfileEngine {",
"  getProfile(userId) {",
"    try {",
"      if (typeof localStorage === 'undefined') return this._defaultProfile(userId);",
"      const raw = localStorage.getItem(STORE_KEY_PREFIX + userId);",
"      return raw ? JSON.parse(raw) : this._defaultProfile(userId);",
"    } catch (e) {",
"      return this._defaultProfile(userId);",
"    }",
"  }",
"",
"  _defaultProfile(userId) {",
"    return {",
"      userId: userId,",
"      role: 'operator',",
"      verticalsUsed: [],",
"      lastActive: null,",
"      preferences: {},",
"    };",
"  }",
"",
"  updateProfile(userId, patch) {",
"    const current = this.getProfile(userId);",
"    const updated = Object.assign({}, current, patch, { lastActive: new Date().toISOString() });",
"    try {",
"      if (typeof localStorage !== 'undefined') {",
"        localStorage.setItem(STORE_KEY_PREFIX + userId, JSON.stringify(updated));",
"      }",
"    } catch (e) {",
"      // ignore storage failures, profile still returned in-memory",
"    }",
"    return updated;",
"  }",
"",
"  recordVerticalUsage(userId, vertical) {",
"    const current = this.getProfile(userId);",
"    const set = new Set(current.verticalsUsed || []);",
"    set.add(vertical);",
"    return this.updateProfile(userId, { verticalsUsed: Array.from(set) });",
"  }",
"}",
"",
"const userProfileEngine = new UserProfileEngine();",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { UserProfileEngine: UserProfileEngine, userProfileEngine: userProfileEngine };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.userProfileEngine = userProfileEngine;",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['behavior-model.js'] = [
"/**",
" * behavior-model.js",
" *",
" * Tracks lightweight, aggregate usage signals per user -- which panels get",
" * opened, how often, and how recently -- to refine the role-based",
" * defaults from role-intelligence.js into something closer to how this",
" * specific person actually works. Intentionally coarse: counts and",
" * timestamps only, no keystroke/content-level tracking.",
" */",
"",
"class BehaviorModel {",
"  constructor() {",
"    this._events = [];",
"  }",
"",
"  recordEvent(userId, eventType, meta) {",
"    this._events.push({",
"      userId: userId,",
"      eventType: eventType,",
"      meta: meta || {},",
"      ts: new Date().toISOString(),",
"    });",
"    if (this._events.length > 10000) {",
"      this._events = this._events.slice(-10000);",
"    }",
"  }",
"",
"  topPanelsForUser(userId, limit) {",
"    const counts = {};",
"    this._events",
"      .filter(function (e) { return e.userId === userId && e.eventType === 'panel_open'; })",
"      .forEach(function (e) {",
"        const panel = e.meta.panel || 'unknown';",
"        counts[panel] = (counts[panel] || 0) + 1;",
"      });",
"    return Object.keys(counts)",
"      .map(function (panel) { return { panel: panel, count: counts[panel] }; })",
"      .sort(function (a, b) { return b.count - a.count; })",
"      .slice(0, limit || 5);",
"  }",
"",
"  lastSeen(userId) {",
"    const userEvents = this._events.filter(function (e) { return e.userId === userId; });",
"    if (!userEvents.length) return null;",
"    return userEvents[userEvents.length - 1].ts;",
"  }",
"}",
"",
"const behaviorModel = new BehaviorModel();",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { BehaviorModel: BehaviorModel, behaviorModel: behaviorModel };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.behaviorModel = behaviorModel;",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['privilege-analyzer.js'] = [
"/**",
" * privilege-analyzer.js",
" *",
" * Read-only analysis over declared roles/permissions (sourced from the",
" * existing Security/Governance layer) to flag privilege drift -- e.g. a",
" * user whose observed behavior no longer matches their declared role, or",
" * permissions that appear unused. This module does not change any",
" * permission; it produces recommendations for a human/admin to act on.",
" */",
"",
"function analyzePrivilegeDrift(userId, deps) {",
"  deps = deps || {};",
"  const userProfileEngine = deps.userProfileEngine;",
"  const behaviorModel = deps.behaviorModel;",
"",
"  if (!userProfileEngine || !behaviorModel) {",
"    throw new Error('privilege-analyzer requires userProfileEngine and behaviorModel');",
"  }",
"",
"  const profile = userProfileEngine.getProfile(userId);",
"  const topPanels = behaviorModel.topPanelsForUser(userId, 10);",
"  const flags = [];",
"",
"  if (profile.role === 'operator' && topPanels.some(function (p) { return /audit|history/i.test(p.panel); })) {",
"    flags.push({",
"      type: 'possible_role_mismatch',",
"      detail: 'User declared as operator but frequently accesses audit/history panels.',",
"      suggestion: 'Consider reviewing whether this user should be reclassified as auditor.',",
"    });",
"  }",
"",
"  if (!profile.verticalsUsed || profile.verticalsUsed.length === 0) {",
"    flags.push({",
"      type: 'unused_access',",
"      detail: 'User has provisioned access but no recorded vertical usage.',",
"      suggestion: 'Confirm access is still needed at next access review.',",
"    });",
"  }",
"",
"  return {",
"    userId: userId,",
"    role: profile.role,",
"    flags: flags,",
"    generatedAt: new Date().toISOString(),",
"  };",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { analyzePrivilegeDrift: analyzePrivilegeDrift };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.analyzePrivilegeDrift = analyzePrivilegeDrift;",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
files['access-recommendation.js'] = [
"/**",
" * access-recommendation.js",
" *",
" * Turns privilege-analyzer flags plus role-intelligence profiles into a",
" * concrete, human-reviewable recommendation queue for admins -- e.g.",
" * 'grant analyst read access to FinOps war room', 'revoke unused",
" * Construction module access'. Recommendations are advisory only; nothing",
" * in this module grants or revokes access.",
" */",
"",
"function buildAccessRecommendations(userId, deps) {",
"  deps = deps || {};",
"  const analyzePrivilegeDrift = deps.analyzePrivilegeDrift;",
"  const getProfileForRole = deps.getProfileForRole;",
"  const userProfileEngine = deps.userProfileEngine;",
"  const behaviorModel = deps.behaviorModel;",
"",
"  const drift = analyzePrivilegeDrift(userId, { userProfileEngine: userProfileEngine, behaviorModel: behaviorModel });",
"  const roleProfile = getProfileForRole(drift.role);",
"",
"  const recommendations = drift.flags.map(function (flag) {",
"    return {",
"      userId: userId,",
"      currentRole: drift.role,",
"      recommendedView: roleProfile.view,",
"      flagType: flag.type,",
"      recommendation: flag.suggestion,",
"      severity: flag.type === 'possible_role_mismatch' ? 'medium' : 'low',",
"      status: 'pending_review',",
"    };",
"  });",
"",
"  return {",
"    userId: userId,",
"    generatedAt: new Date().toISOString(),",
"    recommendations: recommendations,",
"  };",
"}",
"",
"if (typeof module !== 'undefined' && module.exports) {",
"  module.exports = { buildAccessRecommendations: buildAccessRecommendations };",
"}",
"if (typeof window !== 'undefined') {",
"  window.TSM = window.TSM || {};",
"  window.TSM.buildAccessRecommendations = buildAccessRecommendations;",
"}",
""
].join('\n');

// ---------------------------------------------------------------------------
// Installer
// ---------------------------------------------------------------------------

console.log('='.repeat(60));
console.log('TSM Runtime V2 Enterprise Identity & Role Intelligence Installation');
console.log('='.repeat(60));

fs.mkdirSync(ROOT, { recursive: true });

Object.keys(files).forEach(function (name) {
  const target = path.join(ROOT, name);
  fs.writeFileSync(target, files[name], 'utf8');
  console.log('\u2713 ' + target);
});

console.log('Enterprise Identity & Role Intelligence Layer Complete');
