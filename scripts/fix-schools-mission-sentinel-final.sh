p = Path("html/war-rooms/schools-command/schools-command.html")
s = p.read_text()

assert s.count("TSMMissionModel.createMission") >= 1
assert s.count("TSMMissionStore.saveMission") >= 1
assert "classification:" in s
assert "anomalies: anomalies" in s
assert "total_exposure" in s

print("Schools mission assertions: PASS")
PY

echo
echo "============================================================"
echo " SCHOOLS MISSION / SENTINEL PATCH COMPLETE"
echo "============================================================"
echo
