#!/usr/bin/env bash
set -e

echo "==============================================="
echo " TSM ARCHITECTURE KERNEL AUTO REPAIR"
echo "==============================================="

#############################################
# Locate repo root
#############################################

ROOT=$(git rev-parse --show-toplevel 2>/dev/null || true)

if [ -z "$ROOT" ]; then
    echo "ERROR: Not inside a git repository."
    exit 1
fi

cd "$ROOT"

echo
echo "Repo Root:"
echo "$ROOT"

#############################################
# Verify Architecture
#############################################

mkdir -p architecture/kernel

#############################################
# Ensure kernel files exist
#############################################

FILES=(
metadata-engine.js
relevance-engine.js
tsm-registry-verticals.js
intake-gateway-render.js
)

for f in "${FILES[@]}"
do
    if [ ! -f "architecture/kernel/$f" ]; then
        echo "Creating placeholder: $f"

cat > "architecture/kernel/$f" <<EOF
/*
 * $f
 * Placeholder generated by repair script.
 */
export {};
EOF

    fi
done

#############################################
# Patch installer
#############################################

if [ -f apply-intake-gateway.sh ]; then

echo
echo "Patching apply-intake-gateway.sh"

cp apply-intake-gateway.sh apply-intake-gateway.sh.bak

sed -i 's|architecture/metadata-engine.js|$KERNEL_DIR/metadata-engine.js|g' apply-intake-gateway.sh || true
sed -i 's|architecture/relevance-engine.js|$KERNEL_DIR/relevance-engine.js|g' apply-intake-gateway.sh || true
sed -i 's|architecture/tsm-registry-verticals.js|$KERNEL_DIR/tsm-registry-verticals.js|g' apply-intake-gateway.sh || true
sed -i 's|architecture/intake-gateway-render.js|$KERNEL_DIR/intake-gateway-render.js|g' apply-intake-gateway.sh || true

if ! grep -q "KERNEL_DIR=" apply-intake-gateway.sh; then

sed -i '2i\
KERNEL_DIR="${1:-architecture/kernel}"\
ROOT=$(git rev-parse --show-toplevel)\
cd "$ROOT"\
' apply-intake-gateway.sh

fi

chmod +x apply-intake-gateway.sh

fi

#############################################
# Verify prep page
#############################################

echo
echo "Searching for war-room-prep"

PREP=$(find html -name "war-room-prep.html" | head -1)

if [ -n "$PREP" ]; then
    echo "Found:"
    echo "$PREP"
else
    echo
    echo "WARNING"
    echo "war-room-prep.html not found."
fi

#############################################
# Execute installer
#############################################

if [ -x ./apply-intake-gateway.sh ]; then

echo
echo "Running installer..."

./apply-intake-gateway.sh architecture/kernel || true

fi

#############################################
# Verify kernel
#############################################

echo
echo "Kernel"

find architecture/kernel -maxdepth 1 -type f

#############################################
# Repo integrity
#############################################

if [ -f tools/guards/git-integrity-check.sh ]; then

echo
echo "Running integrity check..."

bash tools/guards/git-integrity-check.sh

fi

#############################################
# Git status
#############################################

echo
git status --short

echo
echo "==============================================="
echo " ARCHITECTURE KERNEL READY"
echo "==============================================="
echo
echo "Next:"
echo "  1) Test tsm-doc-search-multi.html"
echo "  2) Verify Process Design Studio"
echo "  3) Finish O2C War Room"
echo "  4) Register additional War Rooms as they are built"