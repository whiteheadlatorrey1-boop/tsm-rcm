#!/usr/bin/env node
// publish-flagship.js
// Publishes the rendered flagship videos into the Demo Console.
//
// render-from-manifest.js writes into tests/e2e/demo/videos/, which is
// git-ignored and not a web folder, so a rendered flagship was never visible
// anywhere. This copies each one into html/demo/flagship/ and writes
// html/demo/flagship/flagship-data.js, which html/demo/tsm-demo-console.html
// loads and lists ahead of the per-vertical demos.
//
// For each experience in demo-readiness.json it takes the narrated render
// (<id>-flagship-narrated.mp4) when there is one, otherwise the silent one.
// Step timings come from the render's own .vtt, so the console's step buttons
// always line up with the video, whatever the narration length was.
//
//   node tests/e2e/demo/publish-flagship.js
//
// Fails if an experience has no rendered video. It does not render anything
// and does not touch visualReview: signing a video off stays a human step.
const fs = require('fs');
const path = require('path');

const DEMO_DIR = __dirname;
const REPO = path.join(DEMO_DIR, '..', '..', '..');
const VIDEOS = path.join(DEMO_DIR, 'videos');
const OUT = path.join(REPO, 'html', 'demo', 'flagship');
const CHAIN = ['War Room', 'Strategist', 'Exec Portal'];

function fail(msg) { console.error('ERROR: ' + msg); process.exit(1); }

function parseVtt(file) {
  const toSec = t => { const [h, m, s] = t.split(':'); return Number(h) * 3600 + Number(m) * 60 + Number(s); };
  const cues = [];
  const blocks = fs.readFileSync(file, 'utf8').split(/\r?\n\r?\n/);
  for (const b of blocks) {
    const lines = b.split(/\r?\n/).filter(Boolean);
    const i = lines.findIndex(l => l.includes('-->'));
    if (i === -1) continue;
    const [from, to] = lines[i].split('-->').map(x => toSec(x.trim()));
    cues.push({ from, to, text: lines.slice(i + 1).join(' ').trim() });
  }
  return cues;
}

// Which chain stage a state is at, from its frame file name.
function stageOf(frameFile) {
  if (/executive/i.test(frameFile)) return 2;
  if (/strategist/i.test(frameFile)) return 1;
  return 0;
}

const registry = JSON.parse(fs.readFileSync(path.join(DEMO_DIR, 'demo-readiness.json'), 'utf8'));
fs.mkdirSync(OUT, { recursive: true });
const entries = [];

for (const exp of registry.experiences) {
  const manifest = JSON.parse(fs.readFileSync(path.join(REPO, exp.manifest), 'utf8'));
  const narratedBase = path.join(VIDEOS, `${exp.id}-flagship-narrated`);
  const silentBase = path.join(VIDEOS, `${exp.id}-flagship`);
  const narrated = fs.existsSync(narratedBase + '.mp4');
  const base = narrated ? narratedBase : silentBase;
  for (const ext of ['.mp4', '.vtt', '.png']) {
    if (!fs.existsSync(base + ext)) fail(`${exp.id}: missing ${path.relative(REPO, base + ext)} — render it first (see tests/e2e/demo/README.md)`);
  }
  const name = `${exp.id}-flagship`;
  for (const ext of ['.mp4', '.vtt', '.png']) fs.copyFileSync(base + ext, path.join(OUT, name + ext));

  const frameDir = path.join(DEMO_DIR, manifest.frameDir);
  const frames = fs.existsSync(frameDir) ? fs.readdirSync(frameDir).filter(f => f.endsWith('.png')).sort() : [];
  const states = manifest.states.filter(s => (s.tiers || []).includes('flagship'));
  const cues = parseVtt(base + '.vtt');
  if (cues.length !== states.length) fail(`${exp.id}: ${cues.length} caption cues for ${states.length} states — re-render`);

  const [head, tail] = manifest.title.replace(/^TSM\s+/, '').split(/:\s*/);
  entries.push({
    id: 'flagship-' + exp.id,
    name: head,
    tag: narrated ? 'FLAGSHIP · NARRATED' : 'FLAGSHIP',
    title: tail || head,
    desc: `${manifest.story.split('>').map(x => x.trim()).join(' → ')}. A scripted scenario: the incident and the engine outputs are simulated.`,
    video: `/demo/flagship/${name}.mp4`,
    poster: `/demo/flagship/${name}.png`,
    captions: `/demo/flagship/${name}.vtt`,
    narrated,
    reviewed: exp.visualReview === true,
    chain: CHAIN,
    steps: states.map((s, i) => {
      const frame = frames.find(f => f.startsWith(String(s.n).padStart(3, '0') + '-')) || '';
      return { t: Math.round(cues[i].from * 10) / 10, chain: stageOf(frame), text: (narrated && s.narration) ? s.narration : s.caption };
    }),
  });
  console.log(`published ${name}${narrated ? ' (narrated)' : ''}`);
}

const banner = '// Generated by tests/e2e/demo/publish-flagship.js. Do not edit by hand: re-run it after a render.\n';
fs.writeFileSync(path.join(OUT, 'flagship-data.js'), banner + 'window.TSM_FLAGSHIP_DATA = ' + JSON.stringify(entries, null, 2) + ';\n');
console.log(`wrote html/demo/flagship/flagship-data.js (${entries.length} experiences)`);
